const DICTS: Record<Lang, Record<TKey, string>> = { de, en };
const STORAGE_KEY = 'tuur.web.lang';

/**
 * Translates a key; `{name}` placeholders are filled from `params`. Unknown keys come back unchanged, which callers
 * use to detect missing translations (e.g. scanner reasons from the server).
 */
export function translate(lang: Lang, key: TKey, params?: Record<string, string | number>): string {
  const raw: string | undefined = DICTS[lang][key] ?? DICTS.de[key];
  if (raw === undefined) return key;
  return params ? raw.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m)) : raw;
}

interface LangState {
  lang: Lang;
  setLang(l: Lang): void;
  t(key: TKey, params?: Record<string, string | number>): string;
}

const LangContext = createContext<LangState | undefined>(undefined);

const detect = (): Lang => {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === 'de' || stored === 'en') return stored;
  } catch {
    // storage blocked: fall back to the browser language
  }
  return (navigator.language ?? '').toLowerCase().startsWith('de') ? 'de' : 'en';
};

export function LangProvider({ children }: { children: ReactNode }) {
  // server render and first client render use German (matches <html lang="de">); the stored choice follows
  const [lang, setLangState] = useState<Lang>('de');

  useEffect(() => {
    setLangState(detect());
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      window.localStorage.setItem(STORAGE_KEY, l);
    } catch {
      // not persisted; the choice still applies to this page view
    }
  }, []);

  const t = useCallback(
    (key: TKey, params?: Record<string, string | number>) => translate(lang, key, params),
    [lang],
  );
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useT(): LangState {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error('useT must be used inside <LangProvider>');
  return ctx;
}
