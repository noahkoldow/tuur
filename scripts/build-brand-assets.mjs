// Regenerates assets/brand/{logo,mark,app} from the high-res sources in assets/brand/source.
// Usage: node scripts/build-brand-assets.mjs (requires `sharp` and `potrace`, installed on demand via pnpm dlx-style: see docs/SETUP.md)
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const sharp = require('sharp');
const potrace = require('potrace');

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'assets', 'brand');
const RED = '#ED0516';
const out = (p) => join(root, p);
for (const d of ['logo', 'mark', 'app']) mkdirSync(out(d), { recursive: true });

const trace = (buf) =>
  new Promise((res, rej) =>
    potrace.trace(buf, { threshold: 128, turdSize: 20, optTolerance: 0.4 }, (e, svg) =>
      e ? rej(e) : res(svg),
    ),
  );

/** Trace a red-on-white source into a single-path SVG description { d, w, h }. */
async function vectorize(file) {
  const trimmed = await sharp(out(`source/${file}`))
    .trim({ background: '#ffffff', threshold: 40 })
    .toBuffer();
  const mono = await sharp(trimmed).extractChannel('green').png().toBuffer();
  const { width: w, height: h } = await sharp(mono).metadata();
  const svg = await trace(mono);
  const d = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(' ');
  return { d, w, h };
}

const svgOf = ({ d, w, h }, fill) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" fill="${fill}"><path d="${d}" fill-rule="evenodd"/></svg>\n`;

const mark = await vectorize('mark-source.webp');
const word = await vectorize('wordmark-source.webp');
const colors = { red: RED, black: '#111111', white: '#FFFFFF' };

for (const [name, fill] of Object.entries(colors)) {
  const wSvg = svgOf(word, fill);
  writeFileSync(out(`logo/tuur-wordmark-${name}.svg`), wSvg);
  await sharp(Buffer.from(wSvg), { density: 300 })
    .resize({ width: 1600 })
    .png()
    .toFile(out(`logo/tuur-wordmark-${name}.png`));
  if (name !== 'black') {
    const mSvg = svgOf(mark, fill);
    writeFileSync(out(`mark/tuur-mark-${name}.svg`), mSvg);
    await sharp(Buffer.from(mSvg), { density: 300 })
      .resize({ width: 1024 })
      .png()
      .toFile(out(`mark/tuur-mark-${name}.png`));
  }
}

/** Mark rendered in `fill`, fitted into a `size` square at `ratio` of its width, on optional background. */
async function markOn(size, ratio, fill, background) {
  const target = Math.round(size * ratio);
  const m = await sharp(Buffer.from(svgOf(mark, fill)), { density: 400 })
    .resize({ width: target, height: target, fit: 'inside' })
    .png()
    .toBuffer();
  return sharp({
    create: {
      width: size,
      height: size,
      channels: 4,
      background: background ?? { r: 0, g: 0, b: 0, alpha: 0 },
    },
  })
    .composite([{ input: m, gravity: 'centre' }])
    .png();
}

await (
  await markOn(1024, 0.58, '#FFFFFF', RED)
)
  .flatten({ background: RED })
  .toFile(out('app/icon-ios-1024.png'));
await (await markOn(1024, 0.5, '#FFFFFF')).toFile(out('app/adaptive-icon-foreground.png'));
await (await markOn(1024, 0.5, '#000000')).toFile(out('app/adaptive-icon-monochrome.png'));
await (await markOn(1024, 0.6, RED)).toFile(out('app/splash-mark.png'));
await (await markOn(96, 0.85, '#FFFFFF')).toFile(out('app/notification-icon.png'));
await (
  await markOn(1024, 0.6, RED, '#FFFFFF')
)
  .flatten({ background: '#FFFFFF' })
  .toFile(out('app/store-mark-on-white.png'));

const fav = {};
for (const s of [16, 32, 48, 180, 192, 512]) {
  const bg = s === 180 ? RED : { r: 0, g: 0, b: 0, alpha: 0 };
  const fill = s === 180 ? '#FFFFFF' : RED;
  const buf = await (await markOn(s, s === 180 ? 0.62 : 0.94, fill, s === 180 ? bg : undefined)).toBuffer();
  fav[s] = buf;
  const name = s === 180 ? 'apple-touch-icon.png' : `favicon-${s}.png`;
  writeFileSync(out(`app/${name}`), buf);
}
writeFileSync(out('app/favicon.svg'), svgOf(mark, RED));

// PNG-in-ICO (16/32/48)
const sizes = [16, 32, 48];
const header = Buffer.alloc(6);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(sizes.length, 4);
let offset = 6 + 16 * sizes.length;
const dirs = sizes.map((s) => {
  const e = Buffer.alloc(16);
  e[0] = s;
  e[1] = s;
  e.writeUInt16LE(1, 4);
  e.writeUInt16LE(32, 6);
  e.writeUInt32LE(fav[s].length, 8);
  e.writeUInt32LE(offset, 12);
  offset += fav[s].length;
  return e;
});
writeFileSync(out('app/favicon.ico'), Buffer.concat([header, ...dirs, ...sizes.map((s) => fav[s])]));
// Single source of truth for the mark geometry used by UI code (web + react-native-svg).
mkdirSync(join(root, '..', '..', 'packages', 'ui', 'src'), { recursive: true });
writeFileSync(
  join(root, '..', '..', 'packages', 'ui', 'src', 'mark.generated.ts'),
  `// GENERATED by scripts/build-brand-assets.mjs - do not edit.\nexport const MARK_VIEWBOX = '0 0 ${mark.w} ${mark.h}';\nexport const MARK_ASPECT_RATIO = ${mark.w} / ${mark.h};\nexport const MARK_PATH =\n  '${mark.d}';\n`,
);
console.log('brand assets written');
